import type { BilingualText, Language } from "./commands/types";

// English is the fallback for incomplete imported or future translations.
export function localize(
  text: Partial<BilingualText>,
  language: Language,
): string {
  return text[language]?.trim() || text.en?.trim() || text.id?.trim() || "";
}

